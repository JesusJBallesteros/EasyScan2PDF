  let lang = 'en';

  function t(key, vars) {
    const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m) : s;
  }

  /* Translates every element marked with data-i18n (text) or data-i18n-title (tooltip). */
  function set(code) {
    lang = STRINGS[code] ? code : 'en';
    document.documentElement.lang = lang;
    for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
    for (const el of document.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  }

  /* The browser's preferred language, when the app has it. */
  function preferred() {
    for (const code of navigator.languages || [navigator.language || 'en']) {
      const short = code.slice(0, 2).toLowerCase();
      if (STRINGS[short]) return short;
    }
    return 'en';
  }

  global.I18n = { t, set, preferred, names: NAMES, get lang() { return lang; } };
